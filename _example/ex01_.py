# ## 문제1. 합격 여부 판정하기

# 학생의 필기 점수와 실기 점수를 입력 받아 합격 여부를 출력하세요.

# **조건**

# - 필기 점수가 60점 이상
# - 실기 점수가 60점 이상
# - 두 조건을 모두 만족하면 “합격입니다.”
# - 하나라도 만족하지 못하면 “불합격입니다.”
필기점수 = int(input('필기점수:'))
실기점수 = int(input('실기점수:'))

print(f'필기점수:{필기점수},type:{type(필기점수)}')
print(f'실기점수:{실기점수},type:{type(실기점수)}')

if 필기점수 >= 60 and 실기점수 >= 60:
    print('합격입니다.')
else:
    print('불합격입니다.')

