def add(a,b):
    """
    두 숫자의 합계를 반환 합니다.

    Args:
        b(integer) : 첫 번째 인자
        b(integar) : 두 번째 인자

        Return:
            int : 두 수의 합계
    """

    return a + b


def subtract(a,b):
    """
    두 숫자의 차이를 반환 합니다.
    """

    return a - b

def multiply(a, b):
    """
    두 숫자의 곱을 반환합니다.
    """
    return a * b

def divide(a, b):
    """
    두 숫자의 나눗셈을 반환합니다.
    """
    return a / b